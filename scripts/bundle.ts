import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';

/** Bundles a browser entry file into one self-contained IIFE string. */
export async function bundleIife(entryPath: string): Promise<string> {
  const result: Bun.BuildOutput = await Bun.build({
    entrypoints: [entryPath],
    target: 'browser',
    format: 'iife',
    minify: false,
  });
  if (!result.success || result.outputs.length !== 1) {
    const messages: string = result.logs.map(String).join('\n');
    throw new Error(`bundling ${entryPath} failed:\n${messages}`);
  }
  const output: Blob | undefined = result.outputs[0];
  return output === undefined ? '' : await output.text();
}

/** Renders the TypeScript module that embeds a bundle as a string constant. */
export function renderGeneratedModule(
  exportName: string,
  entryPath: string,
  source: string
): string {
  return [
    `// Generated by scripts/build-bundles.ts from ${entryPath}. Do not edit.`,
    `export const ${exportName}: string = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

export interface BundleTarget {
  readonly exportName: string;
  readonly entry: string;
  readonly output: string;
}

export const BUNDLE_TARGETS: readonly BundleTarget[] = [
  {
    exportName: 'runtimeSource',
    entry: 'packages/runtime/src/entry.ts',
    output: 'packages/runtime/src/runtimeSource.generated.ts',
  },
  {
    exportName: 'playerClientSource',
    entry: 'packages/player/src/client.ts',
    output: 'packages/player/src/playerClientSource.generated.ts',
  },
];

export const REPO_ROOT: string = path.resolve(import.meta.dir, '..');

/** Builds the expected generated module text for one target. */
export async function renderTarget(target: BundleTarget): Promise<string> {
  const source: string = await bundleIife(path.join(REPO_ROOT, target.entry));
  return renderGeneratedModule(target.exportName, target.entry, source);
}

export interface TextFilesTarget {
  readonly exportName: string;
  readonly directory: string;
  readonly output: string;
}

/** Directories of text files that are embedded as string constants. */
export const TEXT_FILE_TARGETS: readonly TextFilesTarget[] = [
  {
    exportName: 'scorm12SchemaFiles',
    directory: 'packages/exporter-scorm12/schemas',
    output: 'packages/exporter-scorm12/src/schemas.generated.ts',
  },
];

/** Builds the expected generated module text for a directory of `.xsd` files. */
export async function renderTextFilesTarget(
  target: TextFilesTarget
): Promise<string> {
  const directory: string = path.join(REPO_ROOT, target.directory);
  const names: string[] = (await readdir(directory))
    .filter((name: string): boolean => name.endsWith('.xsd'))
    .sort();
  const entries: string[] = [];
  for (const name of names) {
    const text: string = await readFile(path.join(directory, name), 'utf8');
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(text)},`);
  }
  return [
    `// Generated by scripts/build-bundles.ts from ${target.directory}. Do not edit.`,
    `export const ${target.exportName}: Readonly<Record<string, string>> = {`,
    ...entries,
    '};',
    '',
  ].join('\n');
}
